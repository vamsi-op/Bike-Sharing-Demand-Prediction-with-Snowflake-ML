-- BIKE SHARING DEMAND - SNOWFLAKE ML PROJECT
-- Creates infrastructure, loads train.csv, engineers features,
-- and creates chronological train/validation/test tables.

CREATE WAREHOUSE IF NOT EXISTS BIKE_ML_WH
    WAREHOUSE_SIZE = 'X-SMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE;

CREATE DATABASE IF NOT EXISTS BIKE_ML_DB;

CREATE SCHEMA IF NOT EXISTS BIKE_ML_DB.RAW;
CREATE SCHEMA IF NOT EXISTS BIKE_ML_DB.FEATURES;
CREATE SCHEMA IF NOT EXISTS BIKE_ML_DB.ML;
CREATE SCHEMA IF NOT EXISTS BIKE_ML_DB.MONITORING;

USE WAREHOUSE BIKE_ML_WH;
USE DATABASE BIKE_ML_DB;

CREATE OR REPLACE FILE FORMAT BIKE_ML_DB.RAW.BIKE_CSV_FORMAT
    TYPE = CSV
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    TIMESTAMP_FORMAT = 'YYYY-MM-DD HH24:MI:SS';

CREATE STAGE IF NOT EXISTS BIKE_ML_DB.RAW.BIKE_DATA_STAGE
    FILE_FORMAT = BIKE_ML_DB.RAW.BIKE_CSV_FORMAT;

-- Upload train.csv to @BIKE_ML_DB.RAW.BIKE_DATA_STAGE before COPY INTO.

CREATE OR REPLACE TABLE BIKE_ML_DB.RAW.BIKE_DEMAND_RAW (
    DATETIME TIMESTAMP_NTZ,
    SEASON INTEGER,
    HOLIDAY INTEGER,
    WORKINGDAY INTEGER,
    WEATHER INTEGER,
    TEMP FLOAT,
    ATEMP FLOAT,
    HUMIDITY INTEGER,
    WINDSPEED FLOAT,
    CASUAL INTEGER,
    REGISTERED INTEGER,
    COUNT INTEGER
);

COPY INTO BIKE_ML_DB.RAW.BIKE_DEMAND_RAW
FROM @BIKE_ML_DB.RAW.BIKE_DATA_STAGE/train.csv
FILE_FORMAT = (FORMAT_NAME = BIKE_ML_DB.RAW.BIKE_CSV_FORMAT)
ON_ERROR = 'ABORT_STATEMENT';

-- CASUAL and REGISTERED are excluded from model features because
-- COUNT = CASUAL + REGISTERED, which would leak the target.

CREATE OR REPLACE TABLE BIKE_ML_DB.FEATURES.BIKE_DEMAND_FEATURES AS
SELECT
    DATETIME,
    EXTRACT(HOUR FROM DATETIME) AS HOUR,
    EXTRACT(DAY FROM DATETIME) AS DAY,
    EXTRACT(MONTH FROM DATETIME) AS MONTH,
    EXTRACT(YEAR FROM DATETIME) AS YEAR,
    DAYOFWEEK(DATETIME) AS DAY_OF_WEEK,
    SEASON,
    HOLIDAY,
    WORKINGDAY,
    WEATHER,
    TEMP,
    ATEMP,
    HUMIDITY,
    WINDSPEED,
    CASE WHEN DAYOFWEEK(DATETIME) IN (0, 6) THEN 1 ELSE 0 END AS IS_WEEKEND,
    CASE
        WHEN EXTRACT(HOUR FROM DATETIME) IN (7, 8, 9, 16, 17, 18, 19)
             AND WORKINGDAY = 1
        THEN 1 ELSE 0
    END AS RUSH_HOUR,
    COUNT AS TARGET_COUNT
FROM BIKE_ML_DB.RAW.BIKE_DEMAND_RAW;

CREATE OR REPLACE TABLE BIKE_ML_DB.ML.BIKE_DEMAND_ORDERED AS
SELECT *, ROW_NUMBER() OVER (ORDER BY DATETIME) AS ROW_NUM
FROM BIKE_ML_DB.FEATURES.BIKE_DEMAND_FEATURES;

CREATE OR REPLACE TABLE BIKE_ML_DB.ML.BIKE_TRAIN AS
SELECT * FROM BIKE_ML_DB.ML.BIKE_DEMAND_ORDERED WHERE ROW_NUM <= 7620;

CREATE OR REPLACE TABLE BIKE_ML_DB.ML.BIKE_VALIDATION AS
SELECT * FROM BIKE_ML_DB.ML.BIKE_DEMAND_ORDERED
WHERE ROW_NUM > 7620 AND ROW_NUM <= 9255;

CREATE OR REPLACE TABLE BIKE_ML_DB.ML.BIKE_TEST AS
SELECT * FROM BIKE_ML_DB.ML.BIKE_DEMAND_ORDERED WHERE ROW_NUM > 9255;

SELECT 'RAW' AS LAYER, COUNT(*) AS ROW_COUNT
FROM BIKE_ML_DB.RAW.BIKE_DEMAND_RAW
UNION ALL
SELECT 'FEATURES', COUNT(*)
FROM BIKE_ML_DB.FEATURES.BIKE_DEMAND_FEATURES
UNION ALL
SELECT 'TRAIN', COUNT(*)
FROM BIKE_ML_DB.ML.BIKE_TRAIN
UNION ALL
SELECT 'VALIDATION', COUNT(*)
FROM BIKE_ML_DB.ML.BIKE_VALIDATION
UNION ALL
SELECT 'TEST', COUNT(*)
FROM BIKE_ML_DB.ML.BIKE_TEST;
